; ============================================================================
; hello.asm  -  いちばん小さい .COM プログラム
;
; DOS の入口が動いているかの最初の確認。AH=09h で表示し、AH=4Ch で終わる。
; ============================================================================
        bits    16
        org     0x100

        mov     ah, 0x09
        mov     dx, msg
        int     0x21

        mov     ax, 0x4C00              ; 終了コード 0
        int     0x21

msg:    db 'Hello from HELLO.COM', 13, 10, '$'
