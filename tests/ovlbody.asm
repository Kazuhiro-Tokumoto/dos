; ============================================================================
; ovlbody.asm  -  オーバーレイとして読み込まれる側 (AH=4Bh AL=3 の相手)
;
; tools/mkexe.py に食わせて MZ 形式にする。先頭 8 バイトはその表で、
; 呼び出し側はここの最初の word (入口のオフセット) を読んでから far call する。
;
; オーバーレイのリロケーションは「ロード先」ではなく呼び出し側が指定した
; 係数で当てられる。ここではその係数がロード先セグメントと同じになるよう
; 呼び出し側が渡すので、当たっていれば far_ptr のセグメント部が CS と一致する。
; ============================================================================
        cpu     386
        bits    16
        org     0

        dw      entry                   ; 初期 IP (呼び出し側もここを読む)
        dw      0                        ; SP (オーバーレイでは使わない)
        dw      1                        ; リロケーションの数
        dw      reloc_table

reloc_table:
        dw      far_ptr + 2

entry:
        ; リロケーションが当たっていれば、ファイル上 0 だったセグメント部が
        ; いま自分が載っているセグメントになっているはず
        mov     ax, [cs:far_ptr + 2]
        mov     bx, cs
        cmp     ax, bx
        jne     .bad
        mov     ax, 0x5A5A              ; 合言葉
        retf
.bad:
        mov     ax, 0xBAD1
        retf

align 2
far_ptr:
        dw      msg
        dw      0                        ; ← ここがリロケーションで書き換わる
msg:    db      'overlay', 0
